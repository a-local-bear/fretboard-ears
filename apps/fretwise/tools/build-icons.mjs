#!/usr/bin/env node
// Collects the path data of a set of Phosphor icons (MIT licence) into
// public/js/icons.js.  The SVG files are treated as data: only <path d="...">
// attributes made of plain path-data characters are copied.
//
// Usage: node tools/build-icons.mjs <dir with phosphor *-fill.svg / *-bold.svg files>
// Source: https://github.com/phosphor-icons/core (assets/fill, assets/bold)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: node tools/build-icons.mjs <icon-svg-dir>');
  process.exit(2);
}

const SAFE_D = /^[MmLlHhVvCcSsQqTtAaZz0-9eE\s,.\-+]+$/;
const icons = {};
const problems = [];
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(srcDir, file), 'utf8');
  const name = file.replace(/-(fill|bold)\.svg$/, '');
  if (!/viewBox="0 0 256 256"/.test(svg)) { problems.push(`${file}: unexpected viewBox`); continue; }
  const elements = [...svg.matchAll(/<([a-zA-Z]+)\b([^>]*)>/g)].filter((m) => m[1] !== 'svg');
  const ds = [];
  for (const [, tag, attrs] of elements) {
    if (tag !== 'path') { problems.push(`${file}: unsupported element <${tag}>`); continue; }
    const d = /\bd="([^"]*)"/.exec(attrs)?.[1];
    if (!d || !SAFE_D.test(d)) { problems.push(`${file}: path data rejected`); continue; }
    if (/\b(opacity|fill-opacity)=/.test(attrs)) { problems.push(`${file}: translucent layer skipped`); continue; }
    ds.push(d);
  }
  if (!ds.length) { problems.push(`${file}: no usable path`); continue; }
  if (icons[name]) problems.push(`${file}: duplicate icon name ${name}`);
  icons[name] = ds.join('');
}

const banner = `// GENERATED by tools/build-icons.mjs — do not edit by hand.
//
// Icon outlines from Phosphor Icons (https://phosphoricons.com), MIT licence —
// see licenses/Phosphor-MIT.txt.  Each value is SVG path data for a 256x256 viewBox.
`;
const body = 'export const ICONS = {\n' +
  Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') + '\n};\n';
const target = join(here, '..', 'public', 'js', 'icons.js');
writeFileSync(target, banner + '\n' + body);
console.log(`wrote ${Object.keys(icons).length} icons to ${target} (${banner.length + body.length} bytes)`);
if (problems.length) { console.log('notes:'); for (const p of problems) console.log('  ' + p); }
